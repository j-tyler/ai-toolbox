#!/usr/bin/env python3
"""Materialise runnable process versions from the change-intent mechanics files.

A *process version* is a directory the driver can install into a workspace:

    processes/<name>/
      process.json                 which stages run and which files to install
      AGENTS.block.md              appended to the workspace AGENTS.md (optional)
      skills/<skill>/SKILL.md      skills made available to the authoring session
      implementation-guidance.md   appended to the implementing session's system prompt
      review-guidance.md           appended to the process-review session's system prompt (review stage)

The change-intent versions are generated from ../mechanics so there is one
source of truth. Re-run this script after editing the mechanics files. To
experiment with a variant, copy a generated directory to a new name and edit
the copy; the driver treats every directory under processes/ the same way.
"""

from __future__ import annotations

import json
from pathlib import Path

EVAL = Path(__file__).resolve().parents[1]
MECHANICS = EVAL.parent / "mechanics"
PROCESSES = EVAL / "processes"

GENERATED = "<!-- generated by eval/scripts/build_processes.py from mechanics/{src}; edit the source, not this file -->\n\n"


def after_first_rule(path: Path) -> str:
    """Return the agent-facing part of an instrument: everything after the first `---` line."""
    text = path.read_text(encoding="utf-8")
    head, sep, tail = text.partition("\n---\n")
    if not sep:
        raise SystemExit(f"{path} has no horizontal rule separating preamble from instrument")
    return tail.lstrip("\n")


def build_change_intent_v1() -> None:
    out = PROCESSES / "change-intent-v1"
    (out / "skills" / "change-intent-author").mkdir(parents=True, exist_ok=True)

    block = after_first_rule(MECHANICS / "agents-md-block.md")
    block = (
        block.replace("`[/change-intent-author]`", "the `change-intent-author` skill")
        .replace("`[implementation guidance]`", "the change-intent implementation guidance in your instructions")
        .replace("`[your team's review process]`", "the project's review process")
    )
    (out / "AGENTS.block.md").write_text(GENERATED.format(src="agents-md-block.md") + block, encoding="utf-8")

    skill_body = after_first_rule(MECHANICS / "authoring-skill.md")
    frontmatter = (
        "---\n"
        "name: change-intent-author\n"
        "description: Produce an approved change intent through structured dialogue. Use when the author wants to start a change in a project that uses change intents — run this instead of plan mode, not after it.\n"
        "---\n\n"
    )
    (out / "skills" / "change-intent-author" / "SKILL.md").write_text(
        frontmatter + GENERATED.format(src="authoring-skill.md") + skill_body, encoding="utf-8"
    )

    impl = after_first_rule(MECHANICS / "implementation-guidance.md")
    (out / "implementation-guidance.md").write_text(GENERATED.format(src="implementation-guidance.md") + impl, encoding="utf-8")

    review = after_first_rule(MECHANICS / "review-guidance.md")
    (out / "review-guidance.md").write_text(GENERATED.format(src="review-guidance.md") + review, encoding="utf-8")

    (out / "process.json").write_text(
        json.dumps(
            {
                "name": "change-intent-v1",
                "description": "Change intent as drafted in mechanics/: authoring skill with a stand-in author, implementation against the approved intent, then the intent-aware review pass.",
                "stages": ["author", "implement", "review"],
                "agents_block": "AGENTS.block.md",
                "skills_dir": "skills",
                "authoring_skill": "change-intent-author",
                "implementation_guidance": "implementation-guidance.md",
                "review_guidance": "review-guidance.md",
                "intent_dir": "change-intent",
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


def build_baseline() -> None:
    out = PROCESSES / "baseline"
    out.mkdir(parents=True, exist_ok=True)
    (out / "process.json").write_text(
        json.dumps(
            {
                "name": "baseline",
                "description": "No intent. The implementing session receives the brief directly, with the same model, tools, and workspace.",
                "stages": ["implement"],
            },
            indent=2,
        )
        + "\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    build_change_intent_v1()
    build_baseline()
    for p in sorted(PROCESSES.rglob("*")):
        if p.is_file():
            print(p.relative_to(EVAL), p.stat().st_size)
