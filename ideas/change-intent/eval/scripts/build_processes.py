#!/usr/bin/env python3
"""Materialise runnable process versions from the change-intent mechanics files.

A *process version* is a directory under processes/ with a process.json (schema below) and the files it
names. The change-intent versions are generated from ../mechanics so there is one source of truth;
re-run this script after editing the mechanics. To experiment with a variant, copy a generated
directory to a new name and edit the copy, or write a process.json by hand; the driver treats every
directory under processes/ the same way.

process.json schema (every section optional except name):
  name, description
  agents_block            file appended to the workspace AGENTS.md before any stage (null = none)
  author: { mode: "skill" | "frozen" | "none",
            skill, skills_dir,          mode skill: skill name and the directory holding skills/<skill>/SKILL.md
            prompt_file,                optional template with {skill} {intent_dir} {brief}; default is neutral
            frozen_intent,              mode frozen: intent file (relative) to commit without a dialogue
            custom_instructions }       load AGENTS.md etc. in the author session (default true)
  implement: { system_append,           file appended to the implementing session's system prompt
               prompt_file,             optional template with {source} {brief_section} {brief}; default is neutral
               include_brief,           attach the brief alongside the intent (default true)
               custom_instructions }    (default true)
  review: null | { system_append, prompt_file, custom_instructions }   the process's own review pass
  intent: { dir, noun, claim_sections, required_sections }
            where the artifact lives, what the harness calls it ("change intent", "spec", "plan"; default
            "description document"), and which sections hold claims / are required (diagnostics only)
"""

from __future__ import annotations

import json
from pathlib import Path

EVAL = Path(__file__).resolve().parents[1]
MECHANICS = EVAL.parent / "mechanics"
PROCESSES = EVAL / "processes"

GENERATED = "<!-- generated by eval/scripts/build_processes.py from mechanics/{src}; edit the source, not this file -->\n\n"
INTENT = {
    "dir": "change-intent",
    "noun": "change intent",  # how the harness refers to the artifact in its neutral prompts and stand-in replies
    "claim_sections": ["Acceptance criteria", "Invariants"],
    "required_sections": ["Outcomes", "Why", "Constraints", "Acceptance criteria", "Invariants", "Out of scope"],
}
NO_INTENT = {"dir": "change-intent", "noun": "description document", "claim_sections": [], "required_sections": []}


def after_first_rule(path: Path) -> str:
    """Return the agent-facing part of an instrument: everything after the first `---` line."""
    text = path.read_text(encoding="utf-8")
    head, sep, tail = text.partition("\n---\n")
    if not sep:
        raise SystemExit(f"{path} has no horizontal rule separating preamble from instrument")
    return tail.lstrip("\n")


def write_json(path: Path, data: dict) -> None:
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def build_change_intent_v1() -> None:
    out = PROCESSES / "change-intent-v1"
    (out / "skills" / "change-intent-author").mkdir(parents=True, exist_ok=True)

    block = after_first_rule(MECHANICS / "agents-md-block.md")
    block = (
        block.replace("`[/change-intent-author]`", "the `change-intent-author` skill")
        .replace("`[implementation guidance]`", "the change-intent implementation guidance in your instructions")
        .replace("`[your team's review process]`", "the project's review process")
    )
    (out / "AGENTS.block.md").write_text(GENERATED.format(src="agents-md-block.md") + block, encoding="utf-8")

    frontmatter = (
        "---\nname: change-intent-author\n"
        "description: Produce an approved change intent through structured dialogue. Use when the author wants to start a change in a project that uses change intents — run this instead of plan mode, not after it.\n---\n\n"
    )
    (out / "skills" / "change-intent-author" / "SKILL.md").write_text(
        frontmatter + GENERATED.format(src="authoring-skill.md") + after_first_rule(MECHANICS / "authoring-skill.md"), encoding="utf-8")
    (out / "implementation-guidance.md").write_text(
        GENERATED.format(src="implementation-guidance.md") + after_first_rule(MECHANICS / "implementation-guidance.md"), encoding="utf-8")
    (out / "review-guidance.md").write_text(
        GENERATED.format(src="review-guidance.md") + after_first_rule(MECHANICS / "review-guidance.md"), encoding="utf-8")

    write_json(out / "process.json", {
        "name": "change-intent-v1",
        "description": "Change intent as drafted in mechanics/: authoring skill with a stand-in author, implementation against the approved intent with the implementation guidance, then the intent-aware review pass.",
        "agents_block": "AGENTS.block.md",
        "author": {"mode": "skill", "skill": "change-intent-author", "skills_dir": "skills", "custom_instructions": True},
        "implement": {"system_append": "implementation-guidance.md", "include_brief": True, "custom_instructions": True},
        "review": {"system_append": "review-guidance.md", "custom_instructions": True},
        "intent": INTENT,
    })

    # Same guidance, frozen intent: isolates the intent artifact from authoring variance.
    frozen = PROCESSES / "change-intent-v1-frozen"
    frozen.mkdir(parents=True, exist_ok=True)
    for name in ("AGENTS.block.md", "implementation-guidance.md", "review-guidance.md"):
        (frozen / name).write_text((out / name).read_text(encoding="utf-8"), encoding="utf-8")
    write_json(frozen / "process.json", {
        "name": "change-intent-v1-frozen",
        "description": "change-intent-v1 guidance with a pre-authored intent supplied by --intent-file (no authoring dialogue). Use to measure the intent artifact itself, and with include_brief=false to measure the intent alone.",
        "agents_block": "AGENTS.block.md",
        "author": {"mode": "frozen"},
        "implement": {"system_append": "implementation-guidance.md", "include_brief": True, "custom_instructions": True},
        "review": {"system_append": "review-guidance.md", "custom_instructions": True},
        "intent": INTENT,
    })


def build_baseline() -> None:
    out = PROCESSES / "baseline"
    out.mkdir(parents=True, exist_ok=True)
    write_json(out / "process.json", {
        "name": "baseline",
        "description": "No intent. The implementing session receives the brief with the neutral harness prompt, same model, tools, and workspace.",
        "agents_block": None,
        "author": {"mode": "none"},
        "implement": {"system_append": None, "include_brief": True, "custom_instructions": True},
        "review": None,
        "intent": NO_INTENT,
    })


if __name__ == "__main__":
    build_change_intent_v1()
    build_baseline()
    for p in sorted(PROCESSES.rglob("*")):
        if p.is_file():
            print(p.relative_to(EVAL), p.stat().st_size)
